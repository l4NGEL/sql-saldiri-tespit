-- Python tarafında yeniden hesaplanmaz. Özellik OLMAYAN sütunlar (etiket, gün, ayrım,
-- sızıntı bayrakları) yalnızca değerlendirme ve gruplama içindir; model tarafında
-- ids/columns.py:FORBIDDEN_FEATURES ile özellik listesinden dışlandıkları test edilir.
