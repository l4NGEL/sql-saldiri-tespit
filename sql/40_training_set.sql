       c.bwd_header_len,
       c.fwd_pkts_s,
       c.bwd_pkts_s,
       c.pkt_len_min,
       c.pkt_len_max,
       c.pkt_len_mean,
       c.pkt_len_std,
       c.pkt_len_var,
       c.fin_flag_cnt,
       c.syn_flag_cnt,
       c.rst_flag_cnt,
       c.psh_flag_cnt,
       c.ack_flag_cnt,
       c.urg_flag_cnt,
       c.cwe_flag_count,
       c.ece_flag_cnt,
       c.down_up_ratio,
       c.pkt_size_avg,
       c.fwd_seg_size_avg,
       c.bwd_seg_size_avg,
       c.fwd_byts_b_avg,
