JOIN features.flow_features f USING (capture_day, flow_id)
LEFT JOIN features.train_fv_temporal tt ON tt.fv_hash = c.fv_hash
LEFT JOIN features.train_fv_random   tr ON tr.fv_hash = c.fv_hash
