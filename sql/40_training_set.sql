       c.capture_day,
       c.label,
       c.is_attack,
       f.split_temporal,
       f.split_rand,
       (tt.fv_hash IS NOT NULL) AS fv_seen_in_train_temporal,
       (tr.fv_hash IS NOT NULL) AS fv_seen_in_train_random,
       c.dst_port,
       c.protocol,
       c.flow_duration,
       c.tot_fwd_pkts,
