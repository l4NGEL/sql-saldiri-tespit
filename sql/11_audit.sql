-- Tutarsızlık denetimleri (bilgi amaçlı; satır düşürülmez)
INSERT INTO meta.audit(check_name, capture_day, label, value, details)
SELECT 'consistency', capture_day, NULL, cnt, jsonb_build_object('rule', rule)
FROM (
    SELECT capture_day,
           count(*) FILTER (WHERE tot_fwd_pkts > 0 AND abs(totlen_fwd_pkts - tot_fwd_pkts * fwd_pkt_len_mean) > 0.01 * greatest(totlen_fwd_pkts, 1)) AS fwd_len_mismatch,
           count(*) FILTER (WHERE subflow_fwd_pkts <> tot_fwd_pkts) AS subflow_fwd_pkts_ne_total,
           count(*) FILTER (WHERE pkt_len_max < pkt_len_min) AS pkt_len_max_lt_min,
           count(*) FILTER (WHERE flow_duration > 0 AND abs(flow_pkts_s - (tot_fwd_pkts + tot_bwd_pkts) * 1e6 / flow_duration) > 0.01 * greatest(flow_pkts_s, 1)) AS flow_pkts_s_mismatch,
           count(*) FILTER (WHERE flow_duration = 0) AS zero_duration
    FROM raw.flows
    WHERE clean.fix_ts(ts, capture_day) IS NOT NULL AND flow_duration >= 0
    GROUP BY capture_day
) s
CROSS JOIN LATERAL (VALUES ('fwd_len != pkts*mean', fwd_len_mismatch),
                           ('subflow_fwd_pkts != tot_fwd_pkts', subflow_fwd_pkts_ne_total),
                           ('pkt_len_max < pkt_len_min', pkt_len_max_lt_min),
                           ('flow_pkts_s != pkts/duration', flow_pkts_s_mismatch),
                           ('flow_duration = 0 (oranlar tanımsız)', zero_duration)) v(rule, cnt);

