-- Gün x etiket dağılımı (ham)
INSERT INTO meta.audit(check_name, capture_day, label, value)
SELECT 'raw_rows', capture_day, label, count(*) FROM raw.flows GROUP BY 2, 3;

-- Zaman damgası: gün dışı / 1970 kayıtları ve ham saat histogramı (12 saat sorunu için kanıt)
INSERT INTO meta.audit(check_name, capture_day, label, value, details)
SELECT 'raw_hour_hist', capture_day, label, count(*),
       jsonb_build_object('hour', extract(hour FROM ts)::int)
FROM raw.flows WHERE ts::date = capture_day GROUP BY 2, 3, extract(hour FROM ts);

INSERT INTO meta.audit(check_name, capture_day, label, value)
SELECT 'ts_outside_day', capture_day, label, count(*) FROM raw.flows
WHERE ts IS NULL OR ts::date <> capture_day GROUP BY 2, 3;

-- Saldırı etiketlerinin (düzeltilmiş) başlangıç/bitiş saatleri: resmi takvimle karşılaştırma için
